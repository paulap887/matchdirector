const STRINGS: Record<Lang, Record<Key, string>> = { en, fr, es, de, pt, it }

export const isLang = (code: string | null | undefined): code is Lang => LANGS.some((l) => l.code === code)

/** Interface text in the viewer's language, with {placeholders} filled in. */
export function t(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  const text = STRINGS[lang][key]
  return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? '')) : text
}

/** A moment type's label, e.g. "Goal" or "But". */
export const momentLabel = (lang: Lang, type: string): string => (`m.${type}` in en ? t(lang, `m.${type}` as Key) : type)

/** A number in the viewer's locale: "0.35" in English, "0,35" in French. */
export function num(lang: Lang, value: number, digits = 0): string {
  return new Intl.NumberFormat(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(value)
}

/** A 0-100 share in the viewer's locale: "52%" in English, "52 %" in French. */
export function pct(lang: Lang, value: number): string {
  return new Intl.NumberFormat(lang, { style: 'percent', maximumFractionDigits: 0 }).format(value / 100)
}

/** A line the studio wrote, in the viewer's language when a checked translation exists, otherwise in English. */
export function translated(variants: Record<string, string>, key: string, lang: Lang): { text: string; english: boolean } | undefined {
  const local = lang === 'en' ? undefined : variants[`${lang}:${key}`]
  if (local) return { text: local, english: false }
  const english = variants[key]
  return english === undefined ? undefined : { text: english, english: lang !== 'en' }
}
